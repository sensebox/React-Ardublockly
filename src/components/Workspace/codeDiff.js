// The generator writes a timestamp into this comment on every run
const IGNORED_LINE = /^\/\/ Code generated by senseBox Blockly on /;

/**
 * Line based diff used for "code signaling" in the CodeViewer.
 *
 * Returns
 * - `changed`: 1-based line numbers of `newCode` that were added or changed
 *   compared to `oldCode` (blank lines and the timestamp comment excluded)
 * - `lineMap`: maps unchanged 1-based line numbers of `oldCode` to their new
 *   line number in `newCode`
 */
export const diffLines = (oldCode = "", newCode = "") => {
  // Ignored lines are normalised so they always count as unchanged. Otherwise
  // the timestamp in line 1 breaks the prefix match and new lines get matched
  // against identical older lines further up.
  const normalise = (l) => (IGNORED_LINE.test(l) ? "" : l.trimEnd());
  const oldLines = oldCode.split("\n").map(normalise);
  const newLines = newCode.split("\n").map(normalise);

  // Strip common prefix and suffix to keep the LCS table small
  let start = 0;
  while (
    start < oldLines.length &&
    start < newLines.length &&
    oldLines[start] === newLines[start]
  ) {
    start++;
  }
  const lineMap = new Map();
  for (let k = 1; k <= start; k++) lineMap.set(k, k);
  let oldEnd = oldLines.length;
  let newEnd = newLines.length;
  while (
    oldEnd > start &&
    newEnd > start &&
    oldLines[oldEnd - 1] === newLines[newEnd - 1]
  ) {
    lineMap.set(oldEnd, newEnd);
    oldEnd--;
    newEnd--;
  }

  const a = oldLines.slice(start, oldEnd);
  const b = newLines.slice(start, newEnd);
  const n = a.length;
  const m = b.length;

  // LCS table: lcs[i][j] = length of LCS of a[i..] and b[j..]
  const lcs = Array.from({ length: n + 1 }, () => new Uint16Array(m + 1));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      lcs[i][j] =
        a[i] === b[j]
          ? lcs[i + 1][j + 1] + 1
          : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
    }
  }

  // Walk the table; every line of b that is not part of the LCS is new/changed
  const changed = [];
  let i = 0;
  let j = 0;
  while (j < m) {
    if (i < n && a[i] === b[j]) {
      lineMap.set(start + i + 1, start + j + 1);
      i++;
      j++;
    } else if (i < n && lcs[i + 1][j] >= lcs[i][j + 1]) {
      i++;
    } else {
      if (b[j].trim() !== "") changed.push(start + j + 1);
      j++;
    }
  }
  return { changed, lineMap };
};

export const getChangedLines = (oldCode, newCode) =>
  diffLines(oldCode, newCode).changed;

/**
 * Groups sorted line numbers into contiguous ranges [{ start, end }].
 */
export const toLineRanges = (lines) => {
  const ranges = [];
  lines.forEach((line) => {
    const last = ranges[ranges.length - 1];
    if (last && line === last.end + 1) {
      last.end = line;
    } else {
      ranges.push({ start: line, end: line });
    }
  });
  return ranges;
};
